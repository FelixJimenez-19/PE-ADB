CREATE OR REPLACE VIEW farmaciamia.VW_USO_TABLESPACES AS
SELECT D.TABLESPACE_NAME,
       ROUND(D.BYTES / 1024 / 1024, 2) AS TAMANO_MB,
       ROUND(NVL(F.BYTES, 0) / 1024 / 1024, 2) AS LIBRE_MB,
       ROUND((D.BYTES - NVL(F.BYTES, 0)) / 1024 / 1024, 2) AS USADO_MB,
       ROUND((D.BYTES - NVL(F.BYTES, 0)) / D.BYTES * 100, 2) AS PORC_USADO
FROM (SELECT TABLESPACE_NAME, SUM(BYTES) BYTES FROM DBA_DATA_FILES GROUP BY TABLESPACE_NAME) D
LEFT JOIN (SELECT TABLESPACE_NAME, SUM(BYTES) BYTES FROM DBA_FREE_SPACE GROUP BY TABLESPACE_NAME) F
  ON D.TABLESPACE_NAME = F.TABLESPACE_NAME;

