  CONSTRAINT FK_DETVENTA_PRODUCTO FOREIGN KEY (COD_PRODUCTO) REFERENCES PRODUCTO (COD_PRODUCTO),
  CONSTRAINT CK_DETVENTA_CANTIDAD CHECK (CANTIDAD > 0),
  CONSTRAINT CK_DETVENTA_PRECIO CHECK (PRECIO_UNIT >= 0)
);

CREATE SEQUENCE SEQ_VENTA START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE COMPRA (
  NUM_COMPRA    NUMBER(10)    NOT NULL,
