CREATE TABLE SUCURSAL (
  COD_SUCURSAL  NUMBER(3)      NOT NULL,
  NOMBRE        VARCHAR2(50)   NOT NULL,
  CIUDAD        VARCHAR2(50)   NOT NULL,
  DIRECCION     VARCHAR2(100),
  TELEFONO      VARCHAR2(15),
  CONSTRAINT PK_SUCURSAL PRIMARY KEY (COD_SUCURSAL)
);

CREATE TABLE CATEGORIA (
  COD_CATEGORIA NUMBER(3)      NOT NULL,
  NOMBRE        VARCHAR2(50)   NOT NULL,
  DESCRIPCION   VARCHAR2(150),
  CONSTRAINT PK_CATEGORIA PRIMARY KEY (COD_CATEGORIA)
);

CREATE TABLE PROVEEDOR (
  RUC_PROVEEDOR VARCHAR2(13)   NOT NULL,
  NOMBRE        VARCHAR2(100)  NOT NULL,
  TELEFONO      VARCHAR2(15),
  EMAIL         VARCHAR2(100),
  DIRECCION     VARCHAR2(150),
  CONSTRAINT PK_PROVEEDOR PRIMARY KEY (RUC_PROVEEDOR)
);

CREATE TABLE PRODUCTO (
  COD_PRODUCTO    NUMBER(6)     NOT NULL,
  NOMBRE          VARCHAR2(100) NOT NULL,
  DESCRIPCION     VARCHAR2(200),
  PRECIO          NUMBER(10,2)  NOT NULL,
  REQUIERE_RECETA CHAR(1)       DEFAULT 'N' NOT NULL,
  COD_CATEGORIA   NUMBER(3)     NOT NULL,
  RUC_PROVEEDOR   VARCHAR2(13)  NOT NULL,
  CONSTRAINT PK_PRODUCTO PRIMARY KEY (COD_PRODUCTO),
  CONSTRAINT FK_PRODUCTO_CATEGORIA FOREIGN KEY (COD_CATEGORIA) REFERENCES CATEGORIA (COD_CATEGORIA),
  CONSTRAINT FK_PRODUCTO_PROVEEDOR FOREIGN KEY (RUC_PROVEEDOR) REFERENCES PROVEEDOR (RUC_PROVEEDOR),
  CONSTRAINT CK_PRODUCTO_RECETA CHECK (REQUIERE_RECETA IN ('S','N'))
);

CREATE TABLE INVENTARIO (
  COD_INVENTARIO NUMBER(10)    NOT NULL,
  COD_PRODUCTO   NUMBER(6)     NOT NULL,
  COD_SUCURSAL   NUMBER(3)     NOT NULL,
  STOCK          NUMBER(8)     DEFAULT 0 NOT NULL,
  STOCK_MIN      NUMBER(8)     DEFAULT 0 NOT NULL,
  STOCK_MAX      NUMBER(8),
  CONSTRAINT PK_INVENTARIO PRIMARY KEY (COD_INVENTARIO),
  CONSTRAINT FK_INVENTARIO_PRODUCTO FOREIGN KEY (COD_PRODUCTO) REFERENCES PRODUCTO (COD_PRODUCTO),
  CONSTRAINT FK_INVENTARIO_SUCURSAL FOREIGN KEY (COD_SUCURSAL) REFERENCES SUCURSAL (COD_SUCURSAL),
  CONSTRAINT UQ_INVENTARIO_PROD_SUC UNIQUE (COD_PRODUCTO, COD_SUCURSAL),
  CONSTRAINT CK_INVENTARIO_STOCK CHECK (STOCK >= 0)
);

CREATE SEQUENCE SEQ_SUCURSAL   START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_CATEGORIA  START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_PRODUCTO   START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_INVENTARIO START WITH 1 INCREMENT BY 1 NOCACHE;

