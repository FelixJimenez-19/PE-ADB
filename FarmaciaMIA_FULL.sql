CREATE TABLE DETALLE_COMPRA (
  NUM_COMPRA     NUMBER(10)    NOT NULL,
  COD_PRODUCTO   NUMBER(6)     NOT NULL,
  CANTIDAD       NUMBER(6)     NOT NULL,
  PRECIO_COMPRA  NUMBER(10,2)  NOT NULL,
  CONSTRAINT PK_DETALLE_COMPRA PRIMARY KEY (NUM_COMPRA, COD_PRODUCTO),
  CONSTRAINT FK_DETCOMPRA_COMPRA FOREIGN KEY (NUM_COMPRA) REFERENCES COMPRA (NUM_COMPRA),
  CONSTRAINT FK_DETCOMPRA_PRODUCTO FOREIGN KEY (COD_PRODUCTO) REFERENCES PRODUCTO (COD_PRODUCTO),
  CONSTRAINT CK_DETCOMPRA_CANTIDAD CHECK (CANTIDAD > 0),
  CONSTRAINT CK_DETCOMPRA_PRECIO CHECK (PRECIO_COMPRA >= 0)
);

CREATE SEQUENCE SEQ_COMPRA START WITH 1 INCREMENT BY 1 NOCACHE;

-- ============================================================
-- INDICES
-- ============================================================

-- IX_PRODUCTO_CATEGORIA: acelera el JOIN PRODUCTO-CATEGORIA y la validacion
-- de la FK al insertar o actualizar productos.
CREATE INDEX IX_PRODUCTO_CATEGORIA ON PRODUCTO (COD_CATEGORIA);

-- IX_PRODUCTO_PROVEEDOR: acelera el JOIN PRODUCTO-PROVEEDOR y las consultas
-- de "productos por proveedor" para planificar compras.
CREATE INDEX IX_PRODUCTO_PROVEEDOR ON PRODUCTO (RUC_PROVEEDOR);

-- IX_INVENTARIO_PRODUCTO: acelera las consultas de stock por producto y la
-- validacion de la FK de COD_PRODUCTO.
CREATE INDEX IX_INVENTARIO_PRODUCTO ON INVENTARIO (COD_PRODUCTO);

-- IX_INVENTARIO_SUCURSAL: acelera el reporte de inventario por sucursal y la
-- validacion de la FK de COD_SUCURSAL.
CREATE INDEX IX_INVENTARIO_SUCURSAL ON INVENTARIO (COD_SUCURSAL);

-- IX_EMPLEADO_SUCURSAL: acelera listar empleados por sucursal y la FK.
CREATE INDEX IX_EMPLEADO_SUCURSAL ON EMPLEADO (COD_SUCURSAL);

-- IX_VENTA_CLIENTE: acelera el historial de compras por cliente y la FK.
CREATE INDEX IX_VENTA_CLIENTE ON VENTA (CED_CLIENTE);

-- IX_VENTA_EMPLEADO: acelera las ventas por vendedor y la FK.
CREATE INDEX IX_VENTA_EMPLEADO ON VENTA (CED_EMPLEADO);

-- IX_VENTA_SUC_FECHA: indice COMPUESTO. Acelera el reporte de ventas por
-- sucursal y rango de fechas (RF-12) y ademas cubre la FK de COD_SUCURSAL,
-- por lo que no se crea un indice simple aparte para esa FK.
CREATE INDEX IX_VENTA_SUC_FECHA ON VENTA (COD_SUCURSAL, FECHA);

-- IX_DETVENTA_PRODUCTO: acelera la FK y el reporte de productos mas vendidos.
-- (NUM_VENTA ya esta indexado por la PK compuesta, no se duplica.)
CREATE INDEX IX_DETVENTA_PRODUCTO ON DETALLE_VENTA (COD_PRODUCTO);

-- IX_COMPRA_PROVEEDOR: acelera las compras por proveedor y la FK.
CREATE INDEX IX_COMPRA_PROVEEDOR ON COMPRA (RUC_PROVEEDOR);

-- IX_COMPRA_SUCURSAL: acelera las compras por sucursal y la FK.
CREATE INDEX IX_COMPRA_SUCURSAL ON COMPRA (COD_SUCURSAL);

-- IX_DETCOMPRA_PRODUCTO: acelera la FK y el analisis de costo por producto.
-- (NUM_COMPRA ya esta indexado por la PK compuesta, no se duplica.)
CREATE INDEX IX_DETCOMPRA_PRODUCTO ON DETALLE_COMPRA (COD_PRODUCTO);

-- IX_PRODUCTO_NOMBRE: indice SIMPLE. Acelera la busqueda de productos por
-- nombre en el punto de venta (cajero en hora pico).
CREATE INDEX IX_PRODUCTO_NOMBRE ON PRODUCTO (NOMBRE);


